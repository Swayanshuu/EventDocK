/// EventDock Developer Web Platform
///
/// Route overview:
/// - Route '/' renders the actual dashboard (projects overview / selected project dashboard).
/// - Route '/dashboard', '/app', '/projects' also render the dashboard.
/// - Route '/login' exposes the authentication screen.
/// - Route '/waitlist' preserves access to the waitlist landing page.
/// - Any unknown route renders the 404 NotFoundScreen.
class EventDockApp extends StatelessWidget {
  final String? initialRoute;

  const EventDockApp({super.key, this.initialRoute});

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<ThemeMode>(
      valueListenable: AppTheme.themeModeNotifier,
      builder: (context, themeMode, _) {
        return MaterialApp(
          title: 'EventDock - API Failure Detection & Reproduction',
          debugShowCheckedModeBanner: false,
          theme: AppTheme.lightTheme,
          darkTheme: AppTheme.darkTheme,
          themeMode: themeMode,
          initialRoute: initialRoute,
      onGenerateRoute: (RouteSettings settings) {
        final path = normalizeRoute(settings.name);

        // Dedicated Welcome entry route
        if (path == '/welcome') {
          return MaterialPageRoute(
            settings: const RouteSettings(name: '/welcome'),
            builder: (ctx) => WelcomeScreen(
              onGetStarted: () {
                Navigator.pushReplacementNamed(ctx, '/login');
              },
              onSignIn: () {
                Navigator.pushReplacementNamed(ctx, '/login');
              },
            ),
          );
        }

        // Dedicated Waitlist landing page route
        if (path == '/waitlist') {
          return MaterialPageRoute(
            settings: const RouteSettings(name: '/waitlist'),
            builder: (_) => const WaitlistScreen(),
          );
        }

        // Dedicated onboarding route
        if (path == '/onboarding') {
          return MaterialPageRoute(
            settings: const RouteSettings(name: '/onboarding'),
            builder: (_) => OnboardingScreen(
              onComplete: (project) {
                AuthService().completeOnboarding();
              },
              onSignOut: () {
                AuthService().signOut();
              },
            ),
          );
        }

        // Dedicated login route
        if (path == '/login') {
          return MaterialPageRoute(
            settings: const RouteSettings(name: '/login'),
            builder: (_) => AuthScreen(
              onLoginSuccess: () {},
            ),
          );
        }

        // Root and dashboard routes: '/' and '/dashboard', '/app', '/projects'
        if (path == '/' ||
            path.isEmpty ||
            path == '/dashboard' ||
            path == '/app' ||
            path.startsWith('/app/') ||
            path == '/projects') {
          return MaterialPageRoute(
            settings: RouteSettings(name: path),
            builder: (_) => const DashboardRoot(),
          );
        }

        // Unknown routes render 404
        return MaterialPageRoute(
          settings: const RouteSettings(name: '/404'),
          builder: (_) => const NotFoundScreen(),
        );
      },
      onUnknownRoute: (RouteSettings settings) {
        return MaterialPageRoute(
          settings: const RouteSettings(name: '/404'),
          builder: (_) => const NotFoundScreen(),
        );
      },
    );
      },
    );
  }

  /// Normalizes incoming browser paths and URL fragments (e.g. '/#app' or '/app')
  static String normalizeRoute(String? raw) {
    if (raw == null || raw.trim().isEmpty) return '/';
    var clean = raw.trim();

    // Clean hash routing fragments generated by Flutter web
    if (clean.startsWith('/#')) {
      clean = clean.substring(2);
    } else if (clean.startsWith('#')) {
      clean = clean.substring(1);
    }

    final uri = Uri.tryParse(clean);
    final path = uri?.path.isNotEmpty == true ? uri!.path : clean;
    if (path.isEmpty) return '/';
    return path;
  }
}

/// Manages auth state and active project selection within the dashboard
class DashboardRoot extends StatefulWidget {
  const DashboardRoot({super.key});

  @override
  State<DashboardRoot> createState() => _DashboardRootState();
}

class _DashboardRootState extends State<DashboardRoot> {
  Project? _selectedProject;

  @override
  void initState() {
    super.initState();
    AuthService().addListener(_onAuthChanged);
    _syncProjects();
  }

  @override
  void dispose() {
    AuthService().removeListener(_onAuthChanged);
    super.dispose();
  }

  void _onAuthChanged() {
    if (mounted) {
      setState(() {});
      _syncProjects();
    }
  }

  Future<void> _syncProjects() async {
    if (!AuthService().isAuthenticated) return;

    try {
      final list = await ApiService().getProjects();
      if (mounted) {
        setState(() {
          if (list.isNotEmpty) {
            // If currently selected project is still in list, keep it; otherwise pick first real project
            if (_selectedProject == null || !list.any((p) => p.id == _selectedProject!.id)) {
              _selectedProject = list.first;
            }
          } else {
            _selectedProject = null;
          }
        });
      }
    } catch (_) {}
  }

  @override
  Widget build(BuildContext context) {
    if (!AuthService().isAuthenticated) {
      return AuthScreen(
        onLoginSuccess: () {
          setState(() {});
        },
      );
    }

    // Mandatory Firebase Email Verification Gate
    if (!AuthService().isEmailVerified) {
      return EmailVerificationScreen(
        userEmail: AuthService().userEmail ?? '',
        onVerified: () {
          setState(() {});
        },
        onSignOut: () {
          AuthService().signOut();
          setState(() {
            _selectedProject = null;
          });
        },
      );
    }

    if (AuthService().needsOnboarding) {
      return OnboardingScreen(
        onComplete: (project) {
          setState(() {
            _selectedProject = project;
          });
        },
        onSignOut: () {
          AuthService().signOut();
          setState(() {
            _selectedProject = null;
          });
        },
      );
    }

    if (_selectedProject != null) {
      return ProjectDashboardScreen(
        initialProject: _selectedProject!,
        onBackToProjects: () {
          setState(() {
            _selectedProject = null;
          });
        },
        onSignOut: () {
          AuthService().signOut();
          setState(() {
            _selectedProject = null;
          });
        },
      );
    }

    return ProjectsScreen(
      onSelectProject: (project) {
        setState(() {
          _selectedProject = project;
        });
      },
      onSignOut: () {
        AuthService().signOut();
        setState(() {
          _selectedProject = null;
        });
      },
    );
  }
}
